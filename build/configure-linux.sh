#!/bin/sh
# platform: host-agnostic
#   usage: configure-linux.sh SOURCE BUILD PREFIX
set -eu
[ $# -eq 3 ] || { echo 'usage: configure-linux.sh SOURCE BUILD PREFIX' >&2; exit 2; }
exec cmake -G Ninja -S "$1/llvm" -B "$2" \
  -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="$3" \
  -DCMAKE_C_COMPILER=gcc-12 -DCMAKE_CXX_COMPILER=g++-12 \
  '-DCMAKE_EXE_LINKER_FLAGS=-static-libstdc++ -static-libgcc' \
  '-DCMAKE_SHARED_LINKER_FLAGS=-static-libstdc++ -static-libgcc' \
  '-DLLVM_ENABLE_PROJECTS=clang;lld' -DLLVM_ENABLE_RUNTIMES= \
  '-DLLVM_TARGETS_TO_BUILD=X86;AArch64' -DLLVM_PARALLEL_LINK_JOBS=1 \
  -DLLVM_INCLUDE_TESTS=OFF -DLLVM_INCLUDE_EXAMPLES=OFF -DLLVM_INCLUDE_BENCHMARKS=OFF \
  -DLLVM_ENABLE_ZLIB=OFF -DLLVM_ENABLE_ZSTD=OFF -DLLVM_ENABLE_LIBXML2=OFF \
  -DLLVM_ENABLE_LIBEDIT=OFF \
  -DLLVM_LINK_LLVM_DYLIB=OFF -DLLVM_BUILD_LLVM_DYLIB=OFF \
  -DCLANG_DEFAULT_CXX_STDLIB=libc++ -DCLANG_DEFAULT_LINKER=lld -DCLANG_DEFAULT_RTLIB=compiler-rt
